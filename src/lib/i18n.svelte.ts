export const messages: Record<LocaleId, Record<string, string>> = {
  en,
  "pt-BR": ptBR,
};

export type MessageKey = keyof typeof en;

const STORAGE_KEY = "pi.locale";

function detectLocale(): LocaleId {
  try {
    const fromUrl = new URLSearchParams(location.search).get("locale");
    if (fromUrl === "en" || fromUrl === "pt-BR") return fromUrl as LocaleId;
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "pt-BR") return saved;
  } catch {
    /* ignore */
  }
  return "en";
}

let current = $state<LocaleId>(detectLocale());

export function locale(): LocaleId {
  return current;
}

export function setLocale(id: LocaleId) {
  current = id;
  try {
    localStorage.setItem(STORAGE_KEY, id);
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") document.documentElement.lang = id;
}

export function initLocale() {
  if (typeof document !== "undefined") document.documentElement.lang = current;
}

/** Translate a key, interpolating `{name}` placeholders. */
export function t(key: MessageKey | string, vars?: Record<string, string | number>): string {
  const table = messages[current] ?? messages.en;
  let out = table[key as string] ?? messages.en[key as string] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}
